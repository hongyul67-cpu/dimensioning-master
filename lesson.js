/* index.html 의 SVG 함수를 그대로 쓰되, 교실 화면에서 너무 높아지지 않게 눌러 준다 */
function use(fn) {
  return function () {
    var f = window[fn];
    if (typeof f !== 'function') return '';
    /* 배우기 그림은 폰 화면에 맞춘 크기(width="340" 같은 것)로 굳어 있다.
       교실 화면에서는 그대로 두면 너무 작다 — 여는 <svg …> 태그에서 크기 값만
       떼어 내고 viewBox 로 늘린다. 높이는 눌러 두어야 요점 네 줄이 함께 들어온다. */
    var svg = String(f());
    var end = svg.indexOf('>');
    if (end < 0) return '';
    var head = svg.slice(0, end)
                  .replace(/ (?:width|height)="[^"]*"/g, '')
                  .replace(/ style="[^"]*"/g, '');
    return '<div style="width:100%;display:flex;justify-content:center">' +
           head + ' style="width:100%;max-height:30vh;height:auto"' + svg.slice(end) +
           '</div>';
  };
}

